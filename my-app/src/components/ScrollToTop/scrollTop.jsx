import { useEffect } from "react";
import { useLocation } from "react-router-dom";

const ScrollToTop = () => {
  const { pathname } = useLocation();

  useEffect(() => {
    window.scrollTo(0, 0);
  }, [pathname]);

  return null;   // ye kuch render nahi karta, sirf scroll ka kaam karta hai
};

export default ScrollToTop;